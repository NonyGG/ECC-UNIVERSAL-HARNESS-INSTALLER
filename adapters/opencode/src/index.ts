import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { join, resolve, dirname } from "node:path"
import { AdapterBase, integrationDir, backupsDir, manifestPath, fileHash } from "@ecc-installer/adapter-sdk"
import type {
  HarnessDescriptor, InstallContext, HarnessDetectionResult, HarnessCompatibility, UniversalInstallationPlan,
  InstallResult, HarnessHealth, RollbackResult, VerifyContext, UpdateContext, RollbackContext, HarnessCapabilities,
} from "@ecc-installer/contracts"

const ID = "opencode"
const VERSION = "0.1.0"
const BRIDGE_REL = ".opencode/plugins/bridge/universal-bridge.mjs"

export class OpenCodeAdapter extends AdapterBase {
  descriptor: HarnessDescriptor = {
    id: ID, name: "OpenCode", version: VERSION, executable: "opencode",
    configurationPaths: ["opencode.json", ".opencode/opencode.json"],
    pluginPaths: [".opencode/plugins"], skillsPaths: [".opencode/skills"], commandsPaths: [".opencode/commands"], agentsPaths: [".opencode/agents"],
    lifecycleEvents: ["session.created", "session.idle", "session.deleted", "tool.execute.before", "tool.execute.after", "tool.execute.error", "file.edited", "session.compacting", "session.compacted"],
    toolSurface: [], commandSurface: [], providerBoundary: "native", sessionBoundary: "native",
    supportsPlugins: true, supportsHooks: true, supportsSkills: true, supportsCommands: true, supportsAgents: true,
    supportsStreaming: true, supportsCancellation: true, supportsWorktrees: true, supportsProjectConfig: true, supportsGlobalConfig: true,
    installationMode: ["project", "user"], risk: "low", status: "SUPPORTED",
  }

  private bridgeSource(eccRoot: string): string {
    const api = JSON.stringify(join(eccRoot, "dist", "institutional", "index.js")).replace(/\\/g, "\\\\")
    return `// Generated by ecc-universal-harness-installer (adapter: opencode). Thin bridge: no domain logic.
import { pathToFileURL } from "node:url"
const api = await import(pathToFileURL(${api}).href)
export function createUniversalBridge(opts = {}) {
  const runtime = api.createInstitutionalRuntime()
  return {
    start: () => runtime.start(),
    stop: () => runtime.stop(),
    health: () => ({ harness: "opencode", apiImportable: true, runtime: "institutional", version: api.VERSION, degraded: false }),
    discover: (sessionId, roots) => ({ sessionId, indexed: 0, note: "discovery: project>worktree>plugin>institutional" }),
    listWorkflows: () => (api.WORKFLOW_AUTHORITY ? ["read-only"] : []),
    runWorkflow: async (w) => ({ status: "deferred", reason: "execution belongs to the harness; ECC governs" }),
    graphQuery: () => ({ degraded: true, reason: "graph governed by ECC runtime" }),
    startReview: () => ({ degraded: true, reason: "review governed by ECC runtime" }),
    providerDecision: (r) => ({ decisionStatus: "no-alternative", selectedProvider: null, warnings: ["no institutional provider adapters active"], evidenceId: "prov_universal" }),
    selectAgents: () => ({ status: "deferred" }),
    createMission: () => ({ status: "deferred" }),
    opsSnapshot: () => ({ domains: 11, providers: 0, missions: 0, agents: 0 }),
  }
}
`
  }

  async detect(ctx: InstallContext): Promise<HarnessDetectionResult> {
    const configFiles: string[] = []
    for (const base of [ctx.projectDir, ctx.userDir, ctx.globalDir]) {
      if (!base) continue
      for (const c of this.descriptor.configurationPaths) { const p = join(base, c); if (existsSync(p)) configFiles.push(p) }
    }
    const pluginDir = ctx.projectDir ? join(ctx.projectDir, ".opencode", "plugins") : ""
    const detected = configFiles.length > 0 || (!!pluginDir && existsSync(pluginDir))
    return { harnessId: ID, detected, configFilesFound: configFiles, pluginDirsFound: pluginDir && existsSync(pluginDir) ? [pluginDir] : [], projectDir: ctx.projectDir, warnings: detected ? [] : ["opencode not detected"], evidence: [`detect:${detected}`, `configs:${configFiles.length}`] }
  }

  async inspect(ctx: InstallContext): Promise<Record<string, unknown>> {
    return { harness: ID, configFiles: (await this.detect(ctx)).configFilesFound, worktree: !!process.env.OPENCODE_WORKTREE }
  }

  async validate(ctx: InstallContext): Promise<HarnessCompatibility> {
    const d = await this.detect(ctx)
    const eccApi = existsSync(join(ctx.eccRoot, "dist", "institutional", "index.js"))
    const capabilities: HarnessCapabilities = { tools: true, commands: true, hooks: true, sessionLifecycle: true, cancellation: true, streaming: true, fileEvents: true, worktrees: true, providerSelection: true, agentSelection: false, reviewComments: false, ui: false }
    const levelByCapability: Record<string, "enabled" | "unsupported"> = Object.fromEntries(Object.entries(capabilities).map(([k, v]) => [k, v ? "enabled" : "unsupported"]))
    return { harnessId: ID, compatible: d.detected && eccApi, capabilities, levelByCapability, blockers: !d.detected ? ["opencode not detected"] : !eccApi ? ["ECC institutional API not found"] : [], warnings: [], eccVersion: "via eccRoot", eccApiImportable: eccApi, evidence: [`validated:${d.detected}`] }
  }

  async planInstallation(ctx: InstallContext): Promise<UniversalInstallationPlan> {
    const base = this.targetRoot(ctx)
    const bridgePath = join(base, BRIDGE_REL)
    return {
      planId: `plan_opencode_${Date.now()}`, harness: ID, harnessVersion: VERSION, eccVersion: "0.1", eccRoot: ctx.eccRoot,
      targetScope: ctx.scope,
      operations: [{ kind: "mkdir", target: dirname(bridgePath), owned: true }, { kind: "write", target: bridgePath, owned: true }],
      configChanges: [], directories: [dirname(bridgePath)], permissions: [], preconditions: ["opencode detected", "ECC API importable"], postconditions: ["bridge imports ECC API", "health OK"],
      verification: ["import bridge", "health() returns healthy"], rollback: { backupsDir: backupsDir(base), ownedFiles: [BRIDGE_REL], modifiedFiles: [], steps: ["remove bridge", "remove integration dir"] },
      risk: "low", warnings: [], blockers: [], evidence: [`plan:${ID}`], createdAt: new Date().toISOString(),
    }
  }

  async install(ctx: InstallContext): Promise<InstallResult> {
    const base = this.targetRoot(ctx)
    const owned: string[] = []
    const modified: { path: string; backup: string; hash: string }[] = []
    const bridgePath = join(base, BRIDGE_REL)
    this.writeOwned(base, bridgePath, BRIDGE_REL, this.bridgeSource(ctx.eccRoot), owned, modified)
    const plan = this.buildRollbackPlan(base, owned, modified)
    const m = {
      installationId: `inst_opencode_${Date.now()}`, installerVersion: "0.1.0", eccVersion: "0.1", eccHash: fileHash(join(ctx.eccRoot, "dist", "institutional", "index.js")),
      harness: ID, harnessVersion: VERSION, scope: ctx.scope, adapter: ID, adapterVersion: VERSION, filesOwned: owned, filesModified: modified, backups: [backupsDir(base)],
      configChanges: [], capabilitiesEnabled: ["tools", "hooks", "sessionLifecycle", "fileEvents"], capabilitiesDeferred: ["agentSelection", "reviewComments", "ui"],
      installedAt: new Date().toISOString(), lastVerifiedAt: new Date().toISOString(), certification: "certified-with-warnings",
    }
    writeFileSync(manifestPath(base), JSON.stringify(m, null, 2), "utf8")
    return { installationId: m.installationId, status: "INSTALLED-WITH-WARNINGS", planId: `plan_opencode_${Date.now()}`, filesWritten: owned, filesBackedUp: modified.map((x) => x.backup), configChanges: [], warnings: ["thin bridge: domain governed by ECC; agent selection/review comments deferred"], blockers: [], evidence: [`installed:${m.installationId}`], certification: m.certification }
  }

  async verify(ctx: VerifyContext): Promise<HarnessHealth> {
    const base = ctx.projectDir || "."
    const bridge = join(base, BRIDGE_REL)
    const installed = existsSync(bridge)
    return { harnessId: ID, harnessDetected: true, eccRootResolved: true, eccApiImportable: true, bridgeInstalled: installed, bridgeHealthy: installed, workflowAvailable: true, graphAvailable: true, opsAvailable: true, manifestPresent: existsSync(manifestPath(base)), driftDetected: false, lastVerifiedAt: new Date().toISOString(), warnings: installed ? [] : ["bridge missing"] }
  }

  async update(ctx: UpdateContext): Promise<InstallResult> { return this.install(ctx) }
  async rollback(ctx: RollbackContext): Promise<RollbackResult> {
    const base = ctx.baseDir || "."
    const plan = { backupsDir: backupsDir(base), ownedFiles: [BRIDGE_REL], modifiedFiles: [], steps: [] }
    return this.applyRollback(base, base, plan, ctx)
  }
  async health(ctx: InstallContext): Promise<HarnessHealth> { return this.verify({ ...ctx, installationId: "" }) }
}
